using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Ah.Generators;

/// <summary>
/// Emits <c>&lt;RootNamespace&gt;.GeneratedRegistry.Instance</c>, the table of the verbs, hooks, routes, jobs and
/// state domains an assembly declares through the registration attributes of Ah.Abstractions. Registration is
/// resolved at compile time, so nothing scans assemblies at run time.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class RegistryGenerator : IIncrementalGenerator
{
    private const string Abstractions = "Ah.Abstractions.";

    private sealed class Entry(string key, string target, string[] stores, int period)
    {
        public int Period { get; } = period;

        public string Key { get; } = key;

        public string Target { get; } = target;

        public string[] Stores { get; } = stores;
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var verbs = Collect(context, "VerbAttribute", method: true);
        var hooks = Collect(context, "HookAttribute", method: true);
        var routes = Collect(context, "RouteAttribute", method: true);
        var jobs = Collect(context, "JobAttribute", method: true);
        var domains = Collect(context, "StateDomainAttribute", method: false);

        var meta = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.RootNamespace", out var value) ? value : string.Empty)
            .Combine(context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "Ah.Generated"));

        var all = verbs.Combine(hooks).Combine(routes).Combine(jobs).Combine(domains).Combine(meta);

        context.RegisterSourceOutput(all, static (spc, input) =>
        {
            var (((((v, h), r), j), d), (root, assembly)) = input;
            var ns = string.IsNullOrWhiteSpace(root) ? assembly : root;
            spc.AddSource("GeneratedRegistry.g.cs", SourceText.From(Render(ns, v, h, r, j, d), Encoding.UTF8));
        });
    }

    private static IncrementalValueProvider<ImmutableArray<Entry>> Collect(
        IncrementalGeneratorInitializationContext context, string attribute, bool method) =>
        context.SyntaxProvider.ForAttributeWithMetadataName(
                Abstractions + attribute,
                static (node, _) => true,
                (ctx, _) =>
                {
                    var attributeData = ctx.Attributes[0];
                    var key = (string)attributeData.ConstructorArguments[0].Value!;
                    var container = method ? ctx.TargetSymbol.ContainingType : (INamedTypeSymbol)ctx.TargetSymbol;
                    var target = container.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                        .Replace("global::", string.Empty) + (method ? "." + ctx.TargetSymbol.Name : string.Empty);
                    var stores = System.Array.Empty<string>();
                    var period = 0;
                    if (attribute == "JobAttribute")
                    {
                        period = (int)attributeData.ConstructorArguments[1].Value!;
                    }

                    if (!method)
                    {
                        var values = attributeData.ConstructorArguments.Length > 1
                            ? attributeData.ConstructorArguments[1].Values
                            : ImmutableArray<TypedConstant>.Empty;
                        stores = values.Select(static v => (string)v.Value!).ToArray();
                    }

                    return new Entry(key, target, stores, period);
                })
            .Collect();

    private static string Render(
        string ns,
        ImmutableArray<Entry> verbs,
        ImmutableArray<Entry> hooks,
        ImmutableArray<Entry> routes,
        ImmutableArray<Entry> jobs,
        ImmutableArray<Entry> domains)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\nnamespace ").Append(ns).Append(";\n\n");
        sb.Append("internal static class GeneratedRegistry\n{\n");
        sb.Append("    internal static global::Ah.Abstractions.ModuleRegistry Instance { get; } = new(\n");

        AppendList(sb, "global::Ah.Abstractions.VerbRegistration", verbs,
            static e => $"new({Lit(e.Key)}, global::{e.Target})");
        sb.Append(",\n");
        AppendList(sb, "global::Ah.Abstractions.HookRegistration", hooks,
            static e => $"new({Lit(e.Key)}, global::{e.Target})");
        sb.Append(",\n");
        AppendList(sb, "global::Ah.Abstractions.RouteRegistration", routes,
            static e => $"new({Lit(e.Key)}, global::{e.Target})");
        sb.Append(",\n");
        AppendList(sb, "global::Ah.Abstractions.JobRegistration", jobs,
            static e => $"new({Lit(e.Key)}, global::System.TimeSpan.FromMilliseconds({e.Period}), global::{e.Target})");
        sb.Append(",\n");
        AppendList(sb, "global::Ah.Abstractions.StateDomainRegistration", domains,
            static e => $"new({Lit(e.Key)}, new string[] {{ {string.Join(", ", e.Stores.Select(Lit))} }}, {Lit(e.Target)})");

        sb.Append(");\n}\n");
        return sb.ToString();
    }

    private static void AppendList(StringBuilder sb, string type, ImmutableArray<Entry> entries, System.Func<Entry, string> render)
    {
        sb.Append("        new ").Append(type).Append("[] {");
        foreach (var entry in entries.OrderBy(static e => e.Key, System.StringComparer.Ordinal)
                     .ThenBy(static e => e.Target, System.StringComparer.Ordinal))
        {
            sb.Append("\n            ").Append(render(entry)).Append(',');
        }

        sb.Append(" }");
    }

    private static string Lit(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "\\r") + "\"";
}
