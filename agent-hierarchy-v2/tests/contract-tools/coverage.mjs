#!/usr/bin/env node
// Generates tests/contracts/coverage.md: every hooks.json row, verb, route and store that has no case or sample, with the reason.
//   coverage.mjs [--check] [--out FILE]
// --check regenerates and compares with the committed file (exit 1 on a difference). Imports nothing from hooks/ (G2).

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PLUGIN = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const C = join(PLUGIN, "tests", "contracts");
const argv = process.argv.slice(2);
const outPath = argv.includes("--out") ? argv[argv.indexOf("--out") + 1] : join(C, "coverage.md");
const check = argv.includes("--check");

const walk = (d, out = []) => { if (!existsSync(d)) return out; for (const n of readdirSync(d).sort()) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p, out); else out.push(p); } return out; };
const jsonFiles = (d) => walk(d).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(f, "utf8")));
const lines = [];
const out = (s = "") => lines.push(s);

out("# Contract coverage");
out();
out("Generated by `tests/contract-tools/coverage.mjs`; `--check` fails when the committed file is stale. Every row of");
out("`hooks.json`, every verb, every route and every store appears below with its case count, or with the reason it has none.");
out("The allowed reasons for a verb or row without a case are: it needs a real guarded binary, or it needs a live daemon (K1 and");
out("the suite modes cover that). Anything else is a gap and is named as one.");
out();

// ---- hooks
const hooksDoc = JSON.parse(readFileSync(join(PLUGIN, "hooks", "registry.json"), "utf8"));
const rows = [];
for (const [event, groups] of Object.entries(hooksDoc.hooks || hooksDoc)) {
  for (const g of groups) for (const h of g.hooks || []) {
    const m = /ah-hook"? ([A-Za-z0-9._-]+)\s*$/.exec(h.command || "");
    if (m) rows.push({ event, matcher: g.matcher || "*", script: m[1] });
  }
}
const hookCases = jsonFiles(join(C, "hooks"));
const matcherHits = (matcher, tool) => matcher === "*" || !tool || new RegExp(`^(?:${matcher})$`).test(tool);
out(`## Hooks: ${rows.length} rows in hooks/hooks.json`);
out();
out("| Event | Matcher | Script | Cases | Outcomes |");
out("|---|---|---|---|---|");
let rowGaps = 0;
// A gate that exists natively only has no Node recording; the scenario and unit tests named here judge it.
const NATIVE_ONLY = {
  "pretooluse-trust-gate": "native-only gate (no Node recording): lifecycle/14-hook-entry-gates and the Hooks.Tests trust rules",
  "pretooluse-hook-entry-gate": "native-only gate (no Node recording): the Hooks.Tests hook-entry gate rules",
  "pretooluse-anchor-authority-gate": "native-only gate (no Node recording): the Hooks.Tests anchor authority rules",
  "pretooluse-band-token-gate": "native-only gate (no Node recording): the Hooks.Tests band token gate rules",
  "pretooluse-orchestrator-advisor-gate": "native-only gate (no Node recording): the Hooks.Tests orchestrate command rules",
  "pretooluse-worktree-write-gate": "native-only gate (no Node recording): the Hooks.Tests worktree write gate rules",
  "pretooluse-mail-claim": "native-only gate (no Node recording): the Hooks.Tests mail pointer gate rules",
  "posttooluse-commit-log": "native-only recorder (no Node recording): the Hooks.Tests commit log rules",
  "job-track": "native-only recorder (no Node recording): the Hooks.Tests job track rules",
  "stop-member-liveness": "native-only Stop rule (no Node recording): the Hooks.Tests member liveness rules",
  "stop-chain-down": "native-only Stop rule (no Node recording): the Hooks.Tests chain-down rules",
};
for (const r of rows) {
  const mine = hookCases.filter((c) => c.input.script === r.script && c.input.event.hook_event_name === r.event && matcherHits(r.matcher, c.input.event.tool_name));
  const kinds = new Set(mine.filter((c) => c.expect).map((c) => `exit ${c.expect.exit}, ${c.expect.stdout.trim() ? "stdout JSON" : "stdout empty"}`));
  const exempt = mine.length === 0 && NATIVE_ONLY[r.script];
  if (mine.length === 0 && !exempt) rowGaps++;
  out(`| ${r.event} | \`${r.matcher}\` | ${r.script} | ${mine.length} | ${mine.length ? [...kinds].sort().join("; ") : exempt || "**gap: no case**"} |`);
}
out();
out(rowGaps ? `**${rowGaps} rows have no case.**` : "Every row has at least one case.");
out();

// ---- verbs
const verbs = JSON.parse(readFileSync(join(C, "cli", "verbs.json"), "utf8"));
const cliCases = jsonFiles(join(C, "cli", "cases"));
out(`## CLI verbs: ${verbs.length}`);
out();
out("| CLI | Verb | Cases | Exit codes seen | Note |");
out("|---|---|---|---|---|");
let verbGaps = 0;
for (const v of verbs) {
  const mine = cliCases.filter((c) => c.input.cli === v.cli && c.input.argv[0] === v.verb && c.expect);
  const codes = [...new Set(mine.map((c) => c.expect.exit))].sort();
  let note = "";
  if (mine.length === 0) { note = "**gap: no case**"; verbGaps++; }
  else if (!codes.includes(0)) note = (v.spawns || []).some((s) => ["herdr", "tmux", "claude", "codex"].includes(s)) ? "no success case: its working path needs a real guarded binary" : "**gap: only refusals recorded**";
  else if ((v.spawns || []).some((s) => ["herdr", "tmux", "claude", "codex"].includes(s))) note = "success path recorded as a dry run or plan; the launch needs a real guarded binary";
  if (v.cli === "ahd-ctl" && ["start", "restart"].includes(v.verb)) note = "the daemon-off refusal is recorded; the start itself is K5 (needs a live daemon)";
  out(`| ${v.cli} | ${v.verb}${v.sub_verbs ? ` (${v.sub_verbs})` : ""} | ${mine.length} | ${codes.join(", ") || "-"} | ${note} |`);
}
out();
out(verbGaps ? `**${verbGaps} verbs have no case.**` : "Every verb has at least one case.");
out();
// A verb that exists natively only has no Node recording and so is not in verbs.json; the Cli and Hierarchy tests judge it.
const NATIVE_ONLY_VERBS = { progress: "native-only, no Node recording", "msg status": "native-only, no Node recording", "msg history": "native-only, no Node recording", "msg decline": "native-only, no Node recording", "msg withdraw": "native-only, no Node recording", "msg forward": "native-only, no Node recording","msg close": "native-only, no Node recording", "msg next": "native-only, no Node recording", "msg release": "native-only, no Node recording", "msg due": "native-only, no Node recording", "msg history": "native-only, no Node recording","roster wake": "native-only, no Node recording", "roster overdue": "native-only, no Node recording", "roster stall-diagnose": "native-only, no Node recording", "roster checklist": "native-only, no Node recording", "roster team": "native-only, no Node recording" };
out("Verbs with no Node recording (not listed above):");
out();
for (const [verb, why] of Object.entries(NATIVE_ONLY_VERBS)) out(`- ${verb}: ${why}`);
out();

// ---- routes
const routesDoc = JSON.parse(readFileSync(join(C, "wire", "routes.json"), "utf8"));
const routes = Array.isArray(routesDoc) ? routesDoc : routesDoc.routes;
const wireCases = jsonFiles(join(C, "wire", "cases"));
const routeOf = (c) => {
  const p = c.input.path.replace(/\/v1\/join\/.+$/, "/v1/join/{id}").replace(/^\/v1\/state\/[^/]+\/[^/]+$/, "/v1/state/{domain}/{op}");
  return `${c.input.method} ${p}`;
};
out(`## Wire routes: ${routes.length}`);
out();
out("| Route | Cases | 2xx | Statuses seen | Pending |");
out("|---|---|---|---|---|");
for (const r of routes) {
  const key = `${r.method} ${r.path}`;
  const mine = wireCases.filter((c) => routeOf(c) === key);
  const st = [...new Set(mine.filter((c) => c.expect).map((c) => c.expect.status))].sort();
  const pend = mine.filter((c) => c.pending).map((c) => `${c.id} (${c.pending})`);
  out(`| ${key} | ${mine.length} | ${st.some((s) => s >= 200 && s < 300) ? "yes" : "**gap: none**"} | ${st.join(", ") || "-"} | ${pend.join(", ") || "-"} |`);
}
out();
const pendingW2 = wireCases.filter((c) => c.pending);
out(`**Pending W2 (recorded after W2 merges): ${pendingW2.length} cases.** The 413 cases at the cap and the \`/v1/health\` case wait for the 256 KiB cap, the drain-then-close behaviour and \`health.impl\`.`);
out();

// ---- lifecycle
out("## Lifecycle scenarios");
out();
const lc = walk(join(C, "lifecycle")).filter((f) => f.endsWith(".sh") && !/\/_/.test(f));
for (const f of lc) {
  const head = readFileSync(f, "utf8").split("\n").slice(0, 8).join("\n");
  const pend = /^# pending: (\S+)/m.exec(head);
  out(`- \`${f.slice(C.length + 1)}\`: ${pend ? `**pending-${pend[1]}**` : "runs node x node"}`);
}
out();

// ---- stores
const stores = JSON.parse(readFileSync(join(C, "stores.json"), "utf8"));
out(`## Stores: ${stores.length}`);
out();
out("| Store | Class | Samples | Note |");
out("|---|---|---|---|");
for (const s of stores) {
  const note = s.samples && s.samples.length ? "" : s.class === "L" ? "pinned by lifecycle.md and the K5 scenarios" : "no sample yet (see stores-audit.md)";
  out(`| ${s.store} | ${s.class} | ${(s.samples || []).length} | ${note} |`);
}
out();

const text = lines.join("\n") + "\n";
if (check) {
  const have = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (have !== text) { console.log("coverage.md is stale: run tests/contract-tools/coverage.mjs"); process.exit(1); }
  console.log("coverage.md is current");
} else {
  writeFileSync(outPath, text);
  console.log(`coverage: wrote ${outPath} (${rowGaps} hook-row gaps, ${verbGaps} verb gaps)`);
}
